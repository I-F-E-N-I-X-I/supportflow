CREATE TABLE app_user (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username VARCHAR(64) NOT NULL UNIQUE,
 password_hash VARCHAR(100) NOT NULL,
 role VARCHAR(16) NOT NULL CHECK (role IN ('CLIENT','SUPPORT','ADMIN')),
 created_at TIMESTAMPTZ NOT NULL
);
CREATE TABLE user_profile (
 user_id BIGINT PRIMARY KEY REFERENCES app_user(id),
 display_name VARCHAR(100) NOT NULL
);
CREATE TABLE tag (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(40) NOT NULL UNIQUE
);
CREATE TABLE ticket (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 version BIGINT NOT NULL DEFAULT 0,
 client_id BIGINT NOT NULL REFERENCES app_user(id),
 assignee_id BIGINT REFERENCES app_user(id),
 title VARCHAR(160) NOT NULL,
 description VARCHAR(4000) NOT NULL,
 status VARCHAR(16) NOT NULL CHECK(status IN ('NEW','IN_PROGRESS','RESOLVED','CLOSED')),
 priority VARCHAR(16) NOT NULL CHECK(priority IN ('LOW','NORMAL','HIGH','URGENT')),
 compensation NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK(compensation >= 0),
 created_at TIMESTAMPTZ NOT NULL,
 updated_at TIMESTAMPTZ NOT NULL,
 resolved_at TIMESTAMPTZ,
 request_key VARCHAR(80) NOT NULL,
 request_hash VARCHAR(64) NOT NULL,
 UNIQUE(client_id,request_key)
);
CREATE INDEX idx_ticket_client_created ON ticket(client_id,created_at DESC);
CREATE INDEX idx_ticket_filter ON ticket(status,priority,assignee_id);
CREATE TABLE ticket_tag (
 ticket_id BIGINT NOT NULL REFERENCES ticket(id) ON DELETE CASCADE,
 tag_id BIGINT NOT NULL REFERENCES tag(id),
 PRIMARY KEY(ticket_id,tag_id)
);
CREATE TABLE ticket_comment (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ticket_id BIGINT NOT NULL REFERENCES ticket(id),
 author_id BIGINT NOT NULL REFERENCES app_user(id),
 body VARCHAR(2000) NOT NULL,
 internal BOOLEAN NOT NULL,
 created_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_comment_ticket ON ticket_comment(ticket_id,id);
CREATE TABLE status_history (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 ticket_id BIGINT NOT NULL REFERENCES ticket(id),
 actor_id BIGINT NOT NULL REFERENCES app_user(id),
 from_status VARCHAR(16),
 to_status VARCHAR(16) NOT NULL,
 changed_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_history_ticket ON status_history(ticket_id,id);
CREATE TABLE outbox_event (
 id UUID PRIMARY KEY,
 ticket_id BIGINT NOT NULL,
 client_id BIGINT NOT NULL,
 status VARCHAR(16) NOT NULL,
 occurred_at TIMESTAMPTZ NOT NULL,
 published_at TIMESTAMPTZ,
 attempts INTEGER NOT NULL DEFAULT 0,
 next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_outbox_pending ON outbox_event(next_attempt_at) WHERE published_at IS NULL;
